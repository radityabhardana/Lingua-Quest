import { chromium } from 'playwright-core'
import { spawn } from 'node:child_process'

const origin='http://127.0.0.1:4175',chrome='C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe'
const server=spawn(process.execPath,['node_modules/vite/bin/vite.js','preview','--host','127.0.0.1','--port','4175','--strictPort'],{stdio:'pipe'})
const wait=()=>new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(Error('preview timeout')),20000);server.stdout.on('data',data=>{if(data.toString().includes('http://')){clearTimeout(timer);resolve()}})})
const loss=canvas=>canvas.evaluate(element=>{const gl=element.getContext('webgl2')||element.getContext('webgl');const extension=gl?.getExtension('WEBGL_lose_context');if(!extension)throw Error('WEBGL_lose_context unavailable');extension.loseContext()})
try{
  await wait()
  const browser=await chromium.launch({executablePath:chrome,headless:true})
  const page=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,reducedMotion:'reduce'})
  const requests=[],errors=[]
  page.on('request',request=>requests.push(request.url()))
  page.on('pageerror',error=>errors.push(error.message))
  page.on('console',message=>message.type()==='error'&&errors.push(message.text()))
  await page.goto(`${origin}/?atlasDebug=1`,{waitUntil:'networkidle'})
  await page.getByText('Lite Atlas ready').waitFor()
  if(requests.some(url=>/countries-110m|Renderer-|unpkg/.test(url)))throw Error('Lite loaded renderer/topology')
  const afghanistan=page.getByRole('button',{name:'Afghanistan'})
  await afghanistan.click()
  await page.getByRole('heading',{name:'Afghanistan'}).waitFor()
  if(await page.evaluate(()=>document.activeElement?.tagName)!=='H2')throw Error('preview heading did not receive focus')
  await page.getByRole('button',{name:'Albania'}).click()
  await page.keyboard.press('Escape')
  if(await page.evaluate(()=>document.activeElement?.textContent)!=='Afghanistan')throw Error('Escape did not restore original trigger')
  await afghanistan.click()
  await page.getByRole('button',{name:'View countries in this region'}).click()
  if(!await page.getByRole('button',{name:'Show all countries'}).count())throw Error('region filter has no reset')
  await page.getByRole('button',{name:'Show all countries'}).click()
  await page.getByRole('button',{name:'Explore in 3D'}).click()
  const canvas=page.locator('canvas')
  await canvas.waitFor()
  await page.waitForFunction(()=>performance.getEntriesByType('resource').some(entry=>entry.name.includes('countries-110m')))
  if(await canvas.count()!==1)throw Error('expected one Canvas')
  await canvas.scrollIntoViewIfNeeded()
  await page.waitForTimeout(1500)
  const element=await canvas.elementHandle()
  if(!element)throw Error('Canvas element missing')
  if(!await page.waitForFunction(test=>!!test.__atlasProject?.('288'),element,{timeout:5000}).catch(()=>null))throw Error('__atlasProject probe not ready')
  const projected=await canvas.evaluate(el=>el.__atlasProject('288'))
  const atPoint=await page.evaluate(([x,y])=>{const e=document.elementFromPoint(x,y);return `${e?.tagName}.${e?.className}`},[projected.x,projected.y])
  const rect=await canvas.evaluate(element=>{const box=element.getBoundingClientRect();return{x:box.x.toFixed(1),y:box.y.toFixed(1),w:box.width.toFixed(1),h:box.height.toFixed(1)}})
  console.info('[smoke-debug] target=',projected,'rect=',rect,'elementFromPoint=',atPoint)
  const logs=[];page.on('console',message=>logs.push(message.text()))
  // Real Playwright pointer click at the camera-projected center of Ghana's polygon.
  try{await page.mouse.click(projected.x,projected.y)
  await page.locator('.atlas-status').filter({hasText:'Selected: Ghana'}).waitFor()}catch(error){console.info('[smoke-debug-logs]\n'+logs.filter(text=>text.includes('atlas')).join('\n'));throw error}
  const before=await canvas.evaluate(element=>getComputedStyle(element).touchAction)
  await page.getByRole('button',{name:'Capture globe'}).click()
  await page.waitForFunction(test=>getComputedStyle(test).touchAction==='none',element,{timeout:5000})
  const captured=await canvas.evaluate(element=>getComputedStyle(element).touchAction)
  await page.getByRole('button',{name:'Release globe'}).click()
  await page.waitForFunction(test=>getComputedStyle(test).touchAction==='pan-y',element,{timeout:5000})
  const released=await canvas.evaluate(element=>getComputedStyle(element).touchAction)
  if(before!=='pan-y'||captured!=='none'||released!=='pan-y')throw Error('capture touch-action contract failed')
  await loss(canvas)
  await page.getByRole('button',{name:'Retry 3D'}).waitFor()
  if(await canvas.count())throw Error('context loss did not unmount Canvas')
  await page.locator('.atlas-status').filter({hasText:'Selected: Ghana'}).waitFor()
  await page.getByRole('button',{name:'Retry 3D'}).click()
  await canvas.waitFor()
  await loss(canvas)
  await page.locator('.atlas-status').filter({hasText:'Selected: Ghana'}).waitFor()
  if(await page.getByRole('button',{name:/3D/}).count())throw Error('renderer retried more than once')
  await page.getByRole('button',{name:'Ganti bahasa ke Bahasa Indonesia'}).click()
  await page.locator('.atlas-status').filter({hasText:'Dipilih: Ghana'}).waitFor()
  await page.getByText('Afrika Bagian Barat').waitFor()
  const known={'THREE.WebGLRenderer: Cannot read properties of null (reading \'precision\')':true,'Cannot read properties of null (reading \'precision\')':true}
  const unexpected=errors.filter(error=>!Object.keys(known).some(pattern=>error.includes(pattern)))
  if(unexpected.length)throw Error(unexpected.join('|'))
  if(requests.some(url=>!url.startsWith(`${origin}/`)))throw Error('external request')
  const lite=await browser.newPage()
  await lite.addInitScript(()=>{const get=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(kind,...args){return kind==='webgl'||kind==='webgl2'?null:get.call(this,kind,...args)}})
  const liteRequests=[],liteErrors=[]
  lite.on('request',request=>liteRequests.push(request.url()));lite.on('pageerror',error=>liteErrors.push(error.message))
  await lite.goto(origin,{waitUntil:'networkidle'})
  await lite.getByRole('button',{name:'Afghanistan'}).click()
  await lite.getByRole('button',{name:'Explore in 3D'}).click()
  if(await lite.locator('canvas').count()||liteRequests.some(url=>/countries-110m|Renderer-/.test(url))||liteErrors.length)throw Error('no-WebGL fallback downloaded or failed')
  await browser.close()
  console.log(`production smoke passed: ${requests.length} main, ${liteRequests.length} no-WebGL local requests`)
}finally{server.kill()}
