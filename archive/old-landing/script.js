  function stopSpeech() {
    if ("speechSynthesis" in window) window.speechSynthesis.cancel();
    speaking = false;
  }

  function toggleSpeech() {
    if (!("speechSynthesis" in window) || typeof SpeechSynthesisUtterance === "undefined") {
      const error = document.getElementById("audio-error");
      if (error) error.hidden = false;
      announce(d().audioError);
      return;
    }
    if (speaking) {
      stopSpeech();
      renderDemo();
      return;
    }
    const utterance = new SpeechSynthesisUtterance(d().dialogue);
    utterance.lang = "en-US";
    utterance.rate = 0.92;
    utterance.onend = utterance.onerror = () => {
      speaking = false;
      if (state === "dialogue") renderDemo();
    };
    speaking = true;
    renderDemo();
    window.speechSynthesis.speak(utterance);
  }

  demoContent.addEventListener("click", (event) => {
    const button = event.target.closest("[data-action]");
    if (!button) return;
    const action = button.dataset.action;
    if (action === "briefing") setState("briefing", d().announcedBriefing);
    if (action === "dialogue") {
      setState("dialogue", d().announcedDialogue);
      requestAnimationFrame(() => document.getElementById("dialogue-title")?.focus());
    }
    if (action === "audio") toggleSpeech();
    if (action === "meaning") { showMeaning = !showMeaning; renderDemo(); }
    if (action === "choice") setState("choice", d().announcedChoice);
    if (action === "retry") { assisted = false; setState("choice", d().announcedChoice); }
    if (action === "help") {
      selectedChoice = 0;
      assisted = true;
      renderDemo();
      announce(d().helped);
    }
    if (action === "complete") setState("complete", d().announcedComplete);
    if (action === "reset") {
      selectedChoice = null;
      assisted = false;
      setState("idle");
    }
  });

  demoContent.addEventListener("submit", (event) => {
    if (!event.target.matches("[data-demo-form]")) return;
    event.preventDefault();
    const selected = event.target.querySelector("input[name='response']:checked");
    if (!selected) {
      const error = event.target.querySelector("[data-choice-error]");
      error.hidden = false;
      announce(d().selectPrompt);
      return;
    }
    selectedChoice = Number(selected.value);
    assisted = false;
    setState("feedback", `${[d().relevant, d().disconnected, d().incomplete][selectedChoice]}. ${d().explanations[selectedChoice]}`);
  });

